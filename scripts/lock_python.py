"""Write backend/requirements.lock from a resolved environment: exact versions + every sha256 from PyPI.

Usage (resolve first under backend/pip.conf, which enforces the 14-day minimum age):
  python3 -m venv /tmp/resolve && PIP_CONFIG_FILE=backend/pip.conf /tmp/resolve/bin/pip install \\
      --no-require-hashes -r backend/requirements.in
  /tmp/resolve/bin/pip freeze | python3 -I scripts/lock_python.py > backend/requirements.lock
Hashes come from PyPI's JSON API over HTTPS; the upload date of each version is recorded as a comment.
"""
import json
import sys
import urllib.request

PIP = "pip==26.2.2"  # first pip with --uploaded-prior-to; installed from the lock so the venv enforces the age rule


def release(name: str, version: str) -> dict:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:
        return json.load(r)


def main() -> int:
    pins = sorted({line.strip() for line in sys.stdin if "==" in line and not line.startswith("#")} | {PIP}, key=str.lower)
    print("# Generated by scripts/lock_python.py. Install with:")
    print("#   backend/.venv/bin/pip install --require-hashes --no-deps --only-binary :all: -r backend/requirements.lock")
    print("# Every version was resolved under a 14-day minimum release age (backend/pip.conf).")
    for pin in pins:
        name, version = pin.split("==")
        files = release(name, version)["urls"]
        if not files:
            print(f"error: no files for {pin}", file=sys.stderr)
            return 1
        uploaded = min(f["upload_time"] for f in files)[:10]
        hashes = sorted({f["digests"]["sha256"] for f in files})
        print(f"# {name} {version}: uploaded {uploaded}")
        print(f"{name}=={version} \\")
        print(" \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
