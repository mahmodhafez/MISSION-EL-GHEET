"""Export the real planner result for UH-001 into the frontend dev adapter.

Runs packages/meg-core/tools/planner_cli.py on the UH-001 fixture and writes
src/services/dev/uh001.json with:
  - signature: the farmer-entered facts the UI collects (crops, purposes, s1 cut,
    sowings, locks, permissions), taken from the fixture input, so the dev adapter
    only returns this result for exactly that plan;
  - result: the planner's PlanningResult JSON, unchanged.
Re-run after the planner changes:  python3 -I scripts/export_dev_fixture.py
"""
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CORE = ROOT / "packages" / "meg-core"
FIXTURE = CORE / "tools" / "fixtures" / "uh001.json"
OUT = HERE.parent / "src" / "services" / "dev" / "uh001.json"


def value(fact):
    return None if fact is None else fact.get("value")


def main() -> int:
    run = subprocess.run(
        [sys.executable, "-I", str(CORE / "tools" / "planner_cli.py"), "plan", str(FIXTURE), "--json"],
        capture_output=True, text=True, check=False,
    )
    if run.returncode != 0:
        sys.stderr.write(run.stderr or run.stdout)
        return run.returncode
    output = json.loads(run.stdout)
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    inp = fixture["snapshot"]["input"]
    signature = {
        "seasons": [
            {
                "crop_id": value(s["crop_id"]),
                "purpose": value(s["purpose"]),
                "sowing_date": value(s["sowing_date"]),
                # The UI asks the harvest/cut date only for a protected last cut (berseem).
                "last_cut_date": value(s["harvest_or_cut_date"]) if value(s["crop_id"]) == "berseem" else None,
            }
            for s in sorted(inp["seasons"], key=lambda s: s["order"])
        ],
        "commitments": sorted(
            ({"season_id": c["season_id"], "kind": c["kind"], "value": value(c["protected_value"])}
             for c in inp["commitments"] if c["kind"] != "occupation_through"),
            key=lambda c: (c["season_id"], c["kind"]),
        ),
        "choices": [
            {"season_id": c["season_id"], "field": c["field"], "allowed_values": sorted(c["allowed_values"])}
            for c in fixture["exploration"]["choices"]
        ],
    }
    doc = {
        "_note": "Generated by frontend/scripts/export_dev_fixture.py from the real meg_core planner. "
                 "UH-001 is illustrative, not a real farmer. Do not edit by hand.",
        "fixture": "packages/meg-core/tools/fixtures/uh001.json",
        "data_release": output["result"]["scope"]["data_release"],
        "signature": signature,
        "result": output["result"],
    }
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: current={output['result']['current']['status']}, "
          f"review={len(output['result']['review_investigations'])}, "
          f"feasible={len(output['result']['feasible_alternatives'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
